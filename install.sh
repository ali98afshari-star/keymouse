#!/bin/sh
# keymouse installer — Linux Mint / XFCE (X11). No root needed.
# Installs to ~/.local/share/keymouse, launcher to ~/.local/bin/keymouse,
# autostart entry to ~/.config/autostart/keymouse.desktop.
set -eu
SRC_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
DEST="$HOME/.local/share/keymouse"
VENV="$DEST/venv"
BIN="$HOME/.local/bin/keymouse"
CONFIG_DIR="$HOME/.config/keymouse"
CONFIG="$CONFIG_DIR/config.ini"
AUTOSTART_DIR="$HOME/.config/autostart"

command -v python3 >/dev/null || { echo "python3 not found — install it first"; exit 1; }

mkdir -p "$DEST" "$HOME/.local/bin" "$CONFIG_DIR" "$AUTOSTART_DIR" "$HOME/.local/share/applications"
cp "$SRC_DIR/keymouse.py" "$DEST/keymouse.py"
cp "$SRC_DIR/keymouse_gui.py" "$DEST/keymouse_gui.py"
chmod +x "$DEST/keymouse.py" "$DEST/keymouse_gui.py"

# --- python-xlib: prefer a venv, fall back to user site-packages -------
USE_VENV=0
if [ -x "$VENV/bin/python" ] && "$VENV/bin/python" -c "import Xlib" 2>/dev/null; then
    USE_VENV=1
elif python3 -m venv "$VENV" 2>/dev/null; then
    if "$VENV/bin/pip" install --quiet python-xlib; then USE_VENV=1; fi
fi
if [ "$USE_VENV" -eq 0 ]; then
    # venv unavailable (e.g. python3-venv missing): try user install.
    # `sudo apt install python3-venv` then re-running this script is the
    # cleaner fix; this fallback just gets you going.
    if ! python3 -c "import Xlib" 2>/dev/null; then
        python3 -m pip install --user --break-system-packages --quiet python-xlib \
            || { echo "could not install python-xlib; try: sudo apt install python3-venv python3-pip, then re-run install.sh"; exit 1; }
    fi
fi

if [ "$USE_VENV" -eq 1 ]; then
    cat > "$BIN" <<EOF
#!/bin/sh
# keymouse launcher (generated by install.sh)
exec "$VENV/bin/python" "$DEST/keymouse.py" "\$@"
EOF
else
    cat > "$BIN" <<EOF
#!/bin/sh
# keymouse launcher (generated by install.sh)
exec python3 "$DEST/keymouse.py" "\$@"
EOF
fi
chmod +x "$BIN"

# --- settings GUI launcher + menu entry -------------------------------
GUI_BIN="$HOME/.local/bin/keymouse-settings"
if [ "$USE_VENV" -eq 1 ]; then
    cat > "$GUI_BIN" <<EOF
#!/bin/sh
# keymouse-settings launcher (generated by install.sh)
exec "$VENV/bin/python" "$DEST/keymouse_gui.py" "\$@"
EOF
else
    cat > "$GUI_BIN" <<EOF
#!/bin/sh
# keymouse-settings launcher (generated by install.sh)
exec python3 "$DEST/keymouse_gui.py" "\$@"
EOF
fi
chmod +x "$GUI_BIN"
cat > "$HOME/.local/share/applications/keymouse-settings.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=KeyMouse Settings
Comment=Hold a key and move the mouse with the arrow keys — settings
Exec=$GUI_BIN
Terminal=false
Categories=Utility;Settings;
EOF
# tkinter is stdlib but needs python3-tk on some installs; try to fix it.
_TK_PY=python3
[ "$USE_VENV" -eq 1 ] && _TK_PY="$VENV/bin/python"
if ! "$_TK_PY" -c "import tkinter" 2>/dev/null; then
    echo "Note: python3-tk is missing, trying to install it (needs sudo)..."
    sudo apt install -y python3-tk 2>/dev/null || echo "Could not install python3-tk; the settings GUI needs it (sudo apt install python3-tk). The daemon itself still works."
fi

# --- default config (never overwrite an existing one) -----------------
if [ ! -f "$CONFIG" ]; then
    cat > "$CONFIG" <<'EOF'
# keymouse config — edit and restart keymouse (or log out/in).
# modifier: keysym name of the key you HOLD, e.g. Control_R, Caps_Lock,
# Alt_R, Super_R.  Control_R (right Ctrl) is the default: it is rarely
# used by apps, and left Ctrl keeps working normally.
[mouse]
modifier = Control_R
base_speed = 6
max_speed = 42
accel_per_sec = 90
tick_ms = 16
fast_multiplier = 3.0
slow_multiplier = 0.25
scroll_ms = 120
left_click_key = Return
right_click_key = period
middle_click_key = slash
EOF
fi

# --- autostart on login (XFCE: Session and Startup reads this) --------
cat > "$AUTOSTART_DIR/keymouse.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=KeyMouse
Comment=Hold Right Ctrl and move the mouse with the arrow keys
Exec=$BIN
Terminal=false
X-XFCE-Autostart-enabled=true
EOF

# --- restart if it was already running --------------------------------
# Anchored pattern: matches only a process whose command line ENDS with
# keymouse.py (the daemon itself), never a shell that merely mentions it.
for _pid in $(pgrep -f 'keymouse\.py$' 2>/dev/null || true); do
    kill "$_pid" 2>/dev/null || true
done
sleep 0.3
if [ -n "${DISPLAY:-}" ]; then
    nohup "$BIN" > "$DEST/keymouse.log" 2>&1 &
    sleep 0.5
    if pgrep -f "keymouse.py" >/dev/null 2>&1; then
        echo "keymouse is running now. Hold Right Ctrl + arrow keys to move the mouse."
    else
        echo "keymouse did not start — check $DEST/keymouse.log (are you on X11, not Wayland?)"
    fi
else
    echo "Installed. No X display in this shell, so it will start at your next login (autostart is set)."
fi
echo "Launcher: $BIN   |   settings: $GUI_BIN   |   config: $CONFIG   |   test: $BIN --test"
